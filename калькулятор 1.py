a = int(input("введите первое число:"))
c = str(input("введите знак операции:"))
b = int(input("введите второе число:"))

if c == "+":
    print("Результат:", a + b)
elif c == "-":
    print("Результат:", a - b)
elif c == "*":
    print("Результат:", a * b)
elif c == "/":
    if b == 0:
        print("Ошибка: деление на ноль")
    else:
        print("Результат:", a / b)
else:
    print("Ошибка: неизвестная операция")

